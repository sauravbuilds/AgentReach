"""Storage for chats, the search cache and the rate-limit log.

Uses Postgres when DATABASE_URL (or POSTGRES_URL) is set, which is what a hosted deployment needs.
Without it, falls back to a local SQLite file so the app runs on a laptop with no setup.
"""
import os
import re
import sqlite3
import threading
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path


_URL_VAR_RE = re.compile(r"(?:^|_)(?:DATABASE|POSTGRES)_URL$")


def _pg_env_var() -> str | None:
    """Name of the environment variable holding the Postgres connection string, if any.

    Prefers the plain names, then accepts any prefixed one (Vercel can add a prefix such as STORAGE_ when a
    database is connected, giving STORAGE_DATABASE_URL). Pooled URLs are preferred over unpooled ones.
    """
    for name in ("DATABASE_URL", "POSTGRES_URL"):
        if os.environ.get(name, "").startswith(("postgres://", "postgresql://")):
            return name
    candidates = [
        k for k, v in os.environ.items()
        if _URL_VAR_RE.search(k) and v.startswith(("postgres://", "postgresql://")) and "UNPOOLED" not in k and "NON_POOLING" not in k
    ]
    return sorted(candidates)[0] if candidates else None


def _pg_url() -> str:
    name = _pg_env_var()
    return os.environ[name] if name else ""


def _sqlite_path() -> str:
    explicit = os.environ.get("DB_PATH")
    if explicit:
        return explicit
    if os.environ.get("VERCEL"):
        return "/tmp/chats.db"  # temporary disk: history is lost on restart. Set DATABASE_URL for real storage.
    return str(Path(__file__).resolve().parents[2] / "chats.db")


def using_postgres() -> bool:
    return bool(_pg_url())


def postgres_variable_name() -> str | None:
    return _pg_env_var()


def is_persistent() -> bool:
    return bool(_pg_url()) or not os.environ.get("VERCEL")


def _stamp(dt: datetime) -> str:
    return dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ")


def now() -> str:
    return _stamp(datetime.now(timezone.utc))


def ago(seconds: float) -> str:
    return _stamp(datetime.now(timezone.utc) - timedelta(seconds=seconds))


class _Conn:
    def __init__(self, raw, pg: bool):
        self.raw, self.pg = raw, pg

    def run(self, sql: str, params: tuple = ()) -> list[dict]:
        if self.pg:
            sql = sql.replace("?", "%s")
        cur = self.raw.execute(sql, params)
        return [dict(r) for r in cur.fetchall()] if cur.description else []


_ready: set[str] = set()


def _ddl(pg: bool) -> list[str]:
    pk = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if pg else "INTEGER PRIMARY KEY AUTOINCREMENT"
    return [
        f"""CREATE TABLE IF NOT EXISTS chats (
            id {pk}, owner TEXT NOT NULL, title TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL)""",
        "CREATE INDEX IF NOT EXISTS chats_owner_idx ON chats (owner, updated_at)",
        f"""CREATE TABLE IF NOT EXISTS messages (
            id {pk}, chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
            role TEXT NOT NULL, content TEXT NOT NULL, results_json TEXT, created_at TEXT NOT NULL)""",
        "CREATE INDEX IF NOT EXISTS messages_chat_idx ON messages (chat_id, id)",
        """CREATE TABLE IF NOT EXISTS search_cache (
            cache_key TEXT PRIMARY KEY, payload TEXT NOT NULL, created_at TEXT NOT NULL)""",
        f"""CREATE TABLE IF NOT EXISTS search_log (
            id {pk}, owner TEXT NOT NULL, ip TEXT NOT NULL, created_at TEXT NOT NULL)""",
        "CREATE INDEX IF NOT EXISTS search_log_idx ON search_log (created_at)",
    ] + (
        # Hosts like Supabase expose public tables over a web API. Row-level security with no policies
        # blocks that API from reading these tables; the app itself connects directly and is not affected.
        [f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY" for t in ("chats", "messages", "search_cache", "search_log")]
        if pg
        else []
    )


_local = threading.local()


@contextmanager
def connect():
    """Open a connection. Nested calls on the same thread reuse the outer one, so wrapping a whole request
    in `with db.connect():` gives it a single connection (each new connection to a hosted Postgres costs
    a network round trip or more)."""
    shared = getattr(_local, "conn", None)
    if shared is not None:
        yield shared
        return
    with _open() as conn:
        _local.conn = conn
        try:
            yield conn
        finally:
            _local.conn = None


@contextmanager
def _open():
    url = _pg_url()
    if url:
        import psycopg
        from psycopg.rows import dict_row

        raw = psycopg.connect(url, row_factory=dict_row, connect_timeout=10, prepare_threshold=None)
        conn, target = _Conn(raw, True), url
    else:
        raw = sqlite3.connect(_sqlite_path())
        raw.row_factory = sqlite3.Row
        raw.execute("PRAGMA foreign_keys = ON")
        conn, target = _Conn(raw, False), _sqlite_path()
    try:
        if target not in _ready:
            for stmt in _ddl(conn.pg):
                conn.run(stmt)
            raw.commit()
            _ready.add(target)
        yield conn
        raw.commit()
    except Exception:
        raw.rollback()
        raise
    finally:
        raw.close()


# ---- chats (every call is scoped to the owner, so visitors only ever see their own chats) ----

def list_chats(owner: str) -> list[dict]:
    with connect() as c:
        return c.run("SELECT id, title, updated_at FROM chats WHERE owner = ? ORDER BY updated_at DESC LIMIT 200", (owner,))


MAX_CHATS_PER_OWNER = 100


def create_chat(owner: str) -> dict | None:
    """Returns None when the visitor already has the maximum number of chats."""
    with connect() as c:
        if c.run("SELECT COUNT(*) AS n FROM chats WHERE owner = ?", (owner,))[0]["n"] >= MAX_CHATS_PER_OWNER:
            return None
        t = now()
        row = c.run(
            "INSERT INTO chats (owner, title, created_at, updated_at) VALUES (?, 'New chat', ?, ?) RETURNING id",
            (owner, t, t),
        )[0]
    return {"id": row["id"], "title": "New chat"}


def get_chat(owner: str, chat_id: int) -> dict | None:
    with connect() as c:
        rows = c.run("SELECT id, title FROM chats WHERE id = ? AND owner = ?", (chat_id, owner))
        if not rows:
            return None
        msgs = c.run("SELECT * FROM messages WHERE chat_id = ? ORDER BY id", (chat_id,))
    return {**rows[0], "messages": msgs}


def chat_title(owner: str, chat_id: int) -> str | None:
    with connect() as c:
        rows = c.run("SELECT title FROM chats WHERE id = ? AND owner = ?", (chat_id, owner))
    return rows[0]["title"] if rows else None


def rename_chat(owner: str, chat_id: int, title: str) -> bool:
    with connect() as c:
        return bool(c.run("UPDATE chats SET title = ? WHERE id = ? AND owner = ? RETURNING id", (title, chat_id, owner)))


def delete_chat(owner: str, chat_id: int) -> bool:
    with connect() as c:
        return bool(c.run("DELETE FROM chats WHERE id = ? AND owner = ? RETURNING id", (chat_id, owner)))


def add_message(chat_id: int, role: str, content: str, results_json: str | None = None, title: str | None = None) -> dict:
    with connect() as c:
        t = now()
        row = c.run(
            "INSERT INTO messages (chat_id, role, content, results_json, created_at) VALUES (?, ?, ?, ?, ?) RETURNING *",
            (chat_id, role, content, results_json, t),
        )[0]
        if title:
            c.run("UPDATE chats SET title = ?, updated_at = ? WHERE id = ?", (title, t, chat_id))
        else:
            c.run("UPDATE chats SET updated_at = ? WHERE id = ?", (t, chat_id))
    return row


# ---- search cache ----

def cache_get(key: str, ttl_seconds: float) -> str | None:
    with connect() as c:
        rows = c.run("SELECT payload FROM search_cache WHERE cache_key = ? AND created_at > ?", (key, ago(ttl_seconds)))
    return rows[0]["payload"] if rows else None


def cache_put(key: str, payload: str) -> None:
    with connect() as c:
        c.run(
            "INSERT INTO search_cache (cache_key, payload, created_at) VALUES (?, ?, ?) "
            "ON CONFLICT (cache_key) DO UPDATE SET payload = excluded.payload, created_at = excluded.created_at",
            (key, payload, now()),
        )


# ---- rate limiting ----

def recent_searches(owner: str, ip: str, window_seconds: float) -> tuple[int, int]:
    """(searches by this visitor, searches from this IP) within the window."""
    since = ago(window_seconds)
    with connect() as c:
        by_owner = c.run("SELECT COUNT(*) AS n FROM search_log WHERE owner = ? AND created_at > ?", (owner, since))[0]["n"]
        by_ip = c.run("SELECT COUNT(*) AS n FROM search_log WHERE ip = ? AND created_at > ?", (ip, since))[0]["n"]
    return int(by_owner), int(by_ip)


def log_search(owner: str, ip: str) -> None:
    with connect() as c:
        c.run("INSERT INTO search_log (owner, ip, created_at) VALUES (?, ?, ?)", (owner, ip, now()))
        c.run("DELETE FROM search_log WHERE created_at < ?", (ago(2 * 86400),))
